-- 관리자 "수정 요청" 기능용 테이블 + RPC 함수
-- 실행: Supabase SQL Editor 또는 psql. 여러 번 실행해도 안전(IF NOT EXISTS / CREATE OR REPLACE).

CREATE TABLE IF NOT EXISTS public.change_requests (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       text   NOT NULL,
  body        text   NOT NULL DEFAULT '',
  priority    text   NOT NULL DEFAULT '보통',   -- 낮음 / 보통 / 높음
  status      text   NOT NULL DEFAULT '대기',   -- 대기 / 진행중 / 완료 / 보류
  code_name   text,                             -- 첨부 코드 파일명 (선택)
  code        text,                             -- 첨부/붙여넣은 코드 본문 (선택, 저장만 하고 실행하지 않음)
  response    text,                             -- 처리 결과 메모 (Claude/관리자가 기록)
  created_at  bigint NOT NULL,                  -- epoch ms
  done_at     bigint
);

-- 직접 접근 완전 차단: RLS 켜고 정책 없음 + anon/authenticated 권한 회수. RPC(SECURITY DEFINER)로만 접근.
ALTER TABLE public.change_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.change_requests FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.admin_add_request(
  p_password text, p_title text, p_body text, p_priority text, p_code_name text, p_code text
) RETURNS SETOF public.change_requests
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF p_password IS DISTINCT FROM 'admin1388!' THEN
    RAISE EXCEPTION 'unauthorized' USING ERRCODE = '28000';
  END IF;
  IF coalesce(btrim(p_title), '') = '' THEN
    RAISE EXCEPTION 'title required';
  END IF;
  IF length(coalesce(p_code, '')) > 300000 THEN
    RAISE EXCEPTION 'code too large';
  END IF;
  RETURN QUERY
  INSERT INTO change_requests (title, body, priority, code_name, code, created_at)
  VALUES (left(btrim(p_title), 200), left(coalesce(p_body, ''), 20000),
          CASE WHEN p_priority IN ('낮음','보통','높음') THEN p_priority ELSE '보통' END,
          nullif(left(coalesce(p_code_name, ''), 200), ''), nullif(p_code, ''),
          (extract(epoch from now()) * 1000)::bigint)
  RETURNING *;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_list_requests(p_password text)
RETURNS SETOF public.change_requests
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF p_password IS DISTINCT FROM 'admin1388!' THEN
    RAISE EXCEPTION 'unauthorized' USING ERRCODE = '28000';
  END IF;
  RETURN QUERY SELECT * FROM change_requests ORDER BY created_at DESC, id DESC;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_set_request_status(
  p_password text, p_id bigint, p_status text, p_response text DEFAULT NULL
) RETURNS SETOF public.change_requests
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF p_password IS DISTINCT FROM 'admin1388!' THEN
    RAISE EXCEPTION 'unauthorized' USING ERRCODE = '28000';
  END IF;
  IF p_status NOT IN ('대기','진행중','완료','보류') THEN
    RAISE EXCEPTION 'invalid status';
  END IF;
  RETURN QUERY
  UPDATE change_requests
     SET status = p_status,
         response = coalesce(p_response, response),
         done_at = CASE WHEN p_status = '완료' THEN (extract(epoch from now()) * 1000)::bigint ELSE NULL END
   WHERE id = p_id
  RETURNING *;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_delete_request(p_password text, p_id bigint)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF p_password IS DISTINCT FROM 'admin1388!' THEN
    RAISE EXCEPTION 'unauthorized' USING ERRCODE = '28000';
  END IF;
  DELETE FROM change_requests WHERE id = p_id;
END;
$$;

GRANT EXECUTE ON FUNCTION public.admin_add_request(text, text, text, text, text, text) TO anon;
GRANT EXECUTE ON FUNCTION public.admin_list_requests(text) TO anon;
GRANT EXECUTE ON FUNCTION public.admin_set_request_status(text, bigint, text, text) TO anon;
GRANT EXECUTE ON FUNCTION public.admin_delete_request(text, bigint) TO anon;
